// Per-sticker animation rigs for scripts/sprites/build.mjs
//
// Conventions
//   body.dx/dy/rot/sx/sy : 5 values, applied around body.pivot (art units)
//   limbs[].el          : [index of dark stroke, index of colour stroke]
//   limbs[].type        : "rot"  -> rigid swing, angles[] in degrees
//                         "ik"   -> far end re-targeted, targets[] = [dx,dy]
//   limbs[].bendSign    : optional, forces which way an ik limb bows
//   parts[].el          : element indices the prop is made of
//   parts[].translate   : [[dx,dy], ...] per frame
//   parts[].rotate/scale/sx/sy/opacity : 5 values
//   parts[].follow      : index (or indices) of a limb whose hand it sticks to
//   statics             : element indices frozen in the original art position
//
// All rotations are degrees, clockwise on screen (SVG y grows downward).

const N = 5;
const wave = (amp, phase = 0) =>
  Array.from({ length: N }, (_, i) => {
    const v = amp * Math.sin((i / N) * Math.PI * 2 + (phase * Math.PI) / 180);
    return Math.abs(v) < 0.01 ? 0 : +v.toFixed(2);
  });
const S = wave; // starts at 0
const C = (amp, phase = 0) => wave(amp, phase + 90); // starts at amp

